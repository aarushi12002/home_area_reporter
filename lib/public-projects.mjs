export function getPublicProjects(zip, { now = new Date() } = {}) {
  const time = new Date(now).getTime();
  if (!Number.isFinite(time)) return [];
  return projects.filter((project) => project.zip === zip && time >= Date.parse(project.reviewedAt || "2026-10-21") && time < Date.parse(project.reviewUntil || "2027-01-19")).map((project) => ({
    ...project, reviewedAt: project.reviewedAt || "2026-10-21", reviewUntil: project.reviewUntil || "2027-01-19",
    timeline: project.timeline ? {
      ...project.timeline,
      pastTarget: time >= Date.parse(`${project.timeline.targetEnd}T23:59:59.999Z`),
    } : null,
  }));
}
